  function pick(langs) {
    for (const l of langs || []) {
      if (S[l]) return l;
      if (/^pt/i.test(l)) return 'pt-BR';
      if (/^zh/i.test(l)) return 'zh-CN';  // any Chinese reads Simplified for now
      const short = String(l).slice(0, 2).toLowerCase();
      if (S[short]) return short;
    }
    return 'en';
  }
